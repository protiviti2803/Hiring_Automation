    projs = data.get('major_project_experience', [])
    print(f"\n==========================================")
    print(f"Candidate: {j['candidate_name']} ({len(projs)} projects)")
    
    total_buls_gen = sum(len(p.get('bullets', [])) for p in projs)
    print(f"Total bullets generated by LLM: {total_buls_gen}")
    
